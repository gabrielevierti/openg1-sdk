# Accent masks live in row 0; the base glyph is pushed down one row.
_GRAVE = (0x00, 0x01, 0x02, 0x00, 0x00)
_ACUTE = (0x00, 0x00, 0x02, 0x01, 0x00)
_CIRCUMFLEX = (0x00, 0x02, 0x01, 0x02, 0x00)
_DIAERESIS = (0x00, 0x01, 0x00, 0x01, 0x00)
_TILDE = (0x00, 0x02, 0x01, 0x02, 0x01)

_ACCENTS = {
    "grave": _GRAVE,
    "acute": _ACUTE,
    "circumflex": _CIRCUMFLEX,
    "diaeresis": _DIAERESIS,
    "tilde": _TILDE,
}

#: Accented characters, composed from a base glyph plus an accent mask. The
#: Italian set comes first because that is what the author needed; the rest
#: follow the same recipe, so adding a language is one line each.
_COMPOSED: dict[str, tuple[str, str]] = {
    "à": ("a", "grave"), "è": ("e", "grave"), "ì": ("i", "grave"),
    "ò": ("o", "grave"), "ù": ("u", "grave"),
    "á": ("a", "acute"), "é": ("e", "acute"), "í": ("i", "acute"),
    "ó": ("o", "acute"), "ú": ("u", "acute"),
    "â": ("a", "circumflex"), "ê": ("e", "circumflex"), "î": ("i", "circumflex"),
    "ô": ("o", "circumflex"), "û": ("u", "circumflex"),
    "ä": ("a", "diaeresis"), "ë": ("e", "diaeresis"), "ï": ("i", "diaeresis"),
    "ö": ("o", "diaeresis"), "ü": ("u", "diaeresis"),
    "ñ": ("n", "tilde"), "ã": ("a", "tilde"), "õ": ("o", "tilde"),
    "À": ("A", "grave"), "È": ("E", "grave"), "Ì": ("I", "grave"),
    "Ò": ("O", "grave"), "Ù": ("U", "grave"), "É": ("E", "acute"),
}


def _compose(base: str, accent: str) -> tuple[int, ...]:
    """Shift a glyph down one row and stamp an accent above it."""
    body = _BASE[base]
    mask = _ACCENTS[accent]
    return tuple(((column << 1) & 0xFF) | mask[i] for i, column in enumerate(body))


GLYPHS: dict[str, tuple[int, ...]] = dict(_BASE)
for _char, (_base, _accent) in _COMPOSED.items():
    GLYPHS[_char] = _compose(_base, _accent)

#: Drawn for anything the font does not have: a hollow box, the same
#: convention every terminal uses, so a missing glyph looks missing rather
#: than looking like a space.
MISSING: tuple[int, ...] = (0x7F, 0x41, 0x41, 0x41, 0x7F)


def glyph(char: str) -> tuple[int, ...]:
    """The five column bytes for one character."""
    return GLYPHS.get(char, MISSING)


def has_glyph(char: str) -> bool:
    return char in GLYPHS


def advance(x_scale: int = 2, spacing: int = 1) -> int:
    """Horizontal distance from one glyph's origin to the next."""
    return (CELL_WIDTH + spacing) * x_scale


def line_height(y_scale: int = 3, leading: int = 0) -> int:
    return (CELL_HEIGHT + leading) * y_scale


def text_width(text: str, x_scale: int = 2, spacing: int = 1) -> int:
    """Rendered width in pixels, without the trailing inter-glyph gap."""
    if not text:
        return 0
    return len(text) * advance(x_scale, spacing) - spacing * x_scale


def sheet() -> str:
    """Every glyph as ASCII art. Handy for eyeballing the table after edits."""
    rows: list[str] = []
    chars = sorted(GLYPHS)
    for start in range(0, len(chars), 16):
        group = chars[start : start + 16]
        rows.append(" ".join(char.ljust(5) for char in group))
        for row in range(CELL_HEIGHT):
            line = []
            for char in group:
                columns = glyph(char)
                line.append("".join("#" if columns[c] >> row & 1 else "." for c in range(5)))
            rows.append(" ".join(line))
        rows.append("")
    return "\n".join(rows)
