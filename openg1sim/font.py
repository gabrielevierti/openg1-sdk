"""A 5x7 bitmap font, because the panel needs actual pixels.

The G1 firmware does not expose its font, and the glasses render text
themselves — the SDK only ever sends UTF-8. So a simulator that wants to show
what the wearer would see has to draw the glyphs itself.

This is a 5x7 cell font in an 8-row box, so accents sit in row 0 and
descenders in row 7. Each glyph is five column bytes, bit 0 at the top:

    column value 0x7F  ->  a full vertical bar
    column value 0x41  ->  top and bottom pixel only

Horizontal and vertical scale are separate, and by default they differ: 2 wide
by 3 tall, giving 10x24 glyphs on a 12 pixel advance. That is a condensed
look, and it is deliberate. The firmware's font is proportional and averages
about 11 pixels per lowercase character, so a fixed 12 pixel cell fits roughly
40 characters into the panel's 488 pixel text width — close to what the real
display manages. Scaling the glyphs squarely would look prettier and fit only
27, which would report overflow on text that fits the glasses perfectly well.

The accented vowels Italian needs are composed rather than drawn: the base
glyph shifts down a row and an accent mask is added on top. That keeps the
table small and makes it obvious how to add more.
"""

