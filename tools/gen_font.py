#!/usr/bin/env python3
"""Rasterise DejaVu Sans into the 1-bit glyph atlases in src/fontdata.ts.

The G1 panel is monochrome, so anything the SDK draws itself (the Canvas API)
and anything the simulator renders needs real pixels. The firmware's own font
is not published; these atlases are a proportional stand-in with honest
advance widths, generated once and committed so the build needs no fonts.

    python3 tools/gen_font.py        # needs Pillow and DejaVu installed

Record layout, per glyph, inside the base64 blob:
    u16le codepoint, u8 advance, u8 width, u8 height, i8 xoff, i8 yoff,
    then ceil(width*height/8) bytes, bits row-major, MSB first.
DejaVu is distributed under the Bitstream Vera licence, which permits this.
"""
from __future__ import annotations

import base64
import pathlib
import struct

from PIL import ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "fontdata.ts"
DIR = pathlib.Path("/usr/share/fonts/truetype/dejavu")

ASCII = [chr(c) for c in range(0x20, 0x7F)]
LATIN1 = [chr(c) for c in range(0xA1, 0x100) if c != 0xAD]
LATIN_A = [chr(c) for c in range(0x100, 0x180)]
SYMBOLS = list("−€…–—‘’“”•·←↑→↓↔↕↖↗↘↙↰↱↲↳↶↷⇦⇧⇨⇩▲▼◀▶●○■□◆★☆✓✗♥♪⚠⚡☀☁☂№™‰′″≈≠≤≥±×÷∞µΩ")

FONTS = [
    # name, file, px, charset
    ("sm", "DejaVuSans.ttf", 14, ASCII + LATIN1 + LATIN_A + SYMBOLS),
    ("md", "DejaVuSans.ttf", 21, ASCII + LATIN1 + LATIN_A + SYMBOLS),
    # Condensed: the closest match to the advance widths of the firmware's own
    # text, which is what the simulator draws `display.text` screens with.
    ("fw", "DejaVuSansCondensed.ttf", 21, ASCII + LATIN1 + LATIN_A + SYMBOLS),
    ("lg", "DejaVuSans-Bold.ttf", 36, ASCII + LATIN1 + list("−€…–•←↑→↓▲▼◀▶✓✗")),
    ("xl", "DejaVuSans-Bold.ttf", 64, list("0123456789:.,-−+%°/ kmhKMH")),
]


def pack(font: ImageFont.FreeTypeFont, chars: list[str]) -> tuple[bytes, int]:
    notdef, _ = font.getmask2("￿", mode="1")
    notdef_bytes = bytes(notdef)
    blob = bytearray()
    count = 0
    for ch in chars:
        mask, (ox, oy) = font.getmask2(ch, mode="1")
        w, h = mask.size
        data = bytes(mask)
        if ch != " " and (w == 0 or data == notdef_bytes):
            continue  # not in this font: leave it to the missing-glyph box
        advance = round(font.getlength(ch))
        bits = bytearray((w * h + 7) // 8)
        for i, v in enumerate(data):
            if v:
                bits[i >> 3] |= 0x80 >> (i & 7)
        blob += struct.pack("<HBBBbb", ord(ch), advance, w, h, ox, oy) + bits
        count += 1
    return bytes(blob), count


def main() -> None:
    out = [
        "// Generated by tools/gen_font.py from DejaVu Sans. Do not edit.",
        "// DejaVu fonts are (c) Bitstream / DejaVu contributors, Bitstream Vera licence.",
        "",
        "export interface FontBlob {",
        "  name: string;",
        "  size: number;",
        "  ascent: number;",
        "  descent: number;",
        "  lineHeight: number;",
        "  data: string;",
        "}",
        "",
        "export const FONT_BLOBS: Record<string, FontBlob> = {",
    ]
    for name, file, px, chars in FONTS:
        font = ImageFont.truetype(str(DIR / file), px)
        ascent, descent = font.getmetrics()
        blob, count = pack(font, chars)
        b64 = base64.b64encode(blob).decode()
        out.append(
            f'  {name}: {{ name: "{name}", size: {px}, ascent: {ascent}, descent: {descent}, '
            f"lineHeight: {ascent + descent}, data:\n    \"{b64}\" }},"
        )
        print(f"{name}: {px}px, {count} glyphs, {len(blob)} bytes, ascent {ascent} descent {descent}")
    out += ["};", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
