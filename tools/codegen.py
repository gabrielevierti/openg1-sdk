#!/usr/bin/env python3
"""Generate per-language constant tables from protocol/openg1.protocol.yaml.

Every binding shares one opcode table. Editing a generated file by hand will be
undone the next time this runs; edit the YAML instead.

    python3 tools/codegen.py           # write all targets
    python3 tools/codegen.py --check   # fail if anything is stale (used by CI)
"""

from __future__ import annotations

import argparse
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "protocol" / "openg1.protocol.yaml"

BANNER = "Generated by tools/codegen.py from protocol/openg1.protocol.yaml. Do not edit."


def load():
    return yaml.safe_load(SPEC.read_text(encoding="utf-8"))


def hexb(v: int) -> str:
    return f"0x{v:02X}"


def payload_list(cmd) -> list[int]:
    return list(cmd.get("constant_payload") or [])


def enums_sorted(spec):
    for name, members in spec["enums"].items():
        yield name, [(k, v) for k, v in members.items() if not k.startswith("_")]


# --------------------------------------------------------------------------
# Python
# --------------------------------------------------------------------------
def gen_python(spec) -> str:
    t, d = spec["transport"], spec["display"]
    out = [
        '"""' + BANNER + '"""',
        "",
        "from __future__ import annotations",
        "",
        "from enum import IntEnum",
        "from typing import NamedTuple",
        "",
        f'SPEC_VERSION = "{spec["meta"]["spec_version"]}"',
        "",
        "# -- transport ------------------------------------------------------------",
        f'SERVICE_UUID = "{t["service_uuid"]}"',
        f'TX_CHAR_UUID = "{t["tx_char_uuid"]}"',
        f'RX_CHAR_UUID = "{t["rx_char_uuid"]}"',
        f'NAME_PREFIX = "{t["name_prefix"]}"',
        f'NAME_REGEX = r"{t["name_regex"]}"',
        f"DEFAULT_CHUNK = {t['default_chunk']}",
        f"MAX_CHUNK = {t['max_chunk']}",
        f"IDLE_TIMEOUT_S = {t['idle_timeout_s']}",
        f"HEARTBEAT_INTERVAL_S = {t['heartbeat_interval_s']}",
        "",
        "# -- display --------------------------------------------------------------",
        f"DISPLAY_WIDTH = {d['width_px']}",
        f"DISPLAY_HEIGHT = {d['height_px']}",
        f"TEXT_WIDTH = {d['text_width_px']}",
        f"DEFAULT_FONT_PX = {d['default_font_px']}",
        f"DEFAULT_LINES_PER_SCREEN = {d['default_lines_per_screen']}",
        f"BMP_CHUNK_BYTES = {d['bmp_chunk_bytes']}",
        "BMP_STORAGE_ADDRESS = bytes(["
        + ", ".join(hexb(b) for b in d["bmp_storage_address"])
        + "])",
        "",
        "",
        "class Status(IntEnum):",
    ]
    for k, v in spec["status"].items():
        out.append(f"    {k} = {hexb(v)}")
    out += [
        "",
        "",
        "class Arm(IntEnum):",
        "    LEFT = 0",
        "    RIGHT = 1",
        "",
        "    @property",
        "    def label(self) -> str:",
        '        return "L" if self is Arm.LEFT else "R"',
        "",
        "",
        "class Cmd(IntEnum):",
        '    """Opcodes. Names are unique; several opcodes are reused with a',
        '    different constant payload (0x23, 0x2C, 0x26)."""',
        "",
    ]
    seen: dict[int, str] = {}
    aliases = []
    for c in spec["commands"]:
        op = c["opcode"]
        if op in seen:
            aliases.append((c["name"], seen[op]))
        else:
            seen[op] = c["name"]
            out.append(f"    {c['name']} = {hexb(op)}")
    out.append("")
    out.append("")
    out.append("class Evt(IntEnum):")
    eseen: dict[int, str] = {}
    for e in spec["events"]:
        if e["opcode"] in eseen:
            continue
        eseen[e["opcode"]] = e["name"]
        out.append(f"    {e['name']} = {hexb(e['opcode'])}")
    out += [
        "",
        "",
        "class CommandSpec(NamedTuple):",
        "    name: str",
        "    opcode: int",
        "    framed: bool",
        "    target: str          # 'left' | 'right' | 'both'",
        "    response: str        # 'generic' | 'custom' | 'echo_seq' | 'none'",
        "    prefix: bytes        # constant payload sent right after the opcode",
        "    chunked: bool",
        "    confidence: str",
        "    headerless: bool",
        "",
        "",
        "COMMANDS: dict[str, CommandSpec] = {",
    ]
    for c in spec["commands"]:
        pre = payload_list(c)
        prefix = "b''" if not pre else "bytes([" + ", ".join(hexb(b) for b in pre) + "])"
        out.append(
            f'    "{c["name"]}": CommandSpec("{c["name"]}", {hexb(c["opcode"])}, '
            f'{c["framing"] == "framed"}, "{c["target"]}", "{c["response"]}", '
            f'{prefix}, {"chunked" in c}, "{c["confidence"]}", '
            f'{bool(c.get("headerless_response"))}),'
        )
    out.append("}")
    out.append("")
    for name, members in enums_sorted(spec):
        vals = [v for _, v in members]
        if all(isinstance(v, int) for v in vals):
            out += ["", f"class {name}(IntEnum):"]
            emitted = set()
            for k, v in members:
                if v in emitted:
                    out.append(f"    # {k} duplicates {hexb(v)}")
                    continue
                emitted.add(v)
                out.append(f"    {k} = {hexb(v)}")
        else:
            out += ["", f"class {name}:"]
            for k, v in members:
                out.append(f'    {k} = "{v}"')
    out.append("")
    return "\n".join(out)


