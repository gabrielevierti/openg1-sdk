def gen_c_header(spec) -> str:
    t, d = spec["transport"], spec["display"]
    out = [
        f"/* {BANNER} */",
        "#ifndef OG1_OPCODES_H",
        "#define OG1_OPCODES_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        f'#define OG1_SPEC_VERSION "{spec["meta"]["spec_version"]}"',
        "",
        f'#define OG1_SERVICE_UUID "{t["service_uuid"]}"',
        f'#define OG1_TX_CHAR_UUID "{t["tx_char_uuid"]}"',
        f'#define OG1_RX_CHAR_UUID "{t["rx_char_uuid"]}"',
        f'#define OG1_NAME_PREFIX  "{t["name_prefix"]}"',
        f"#define OG1_DEFAULT_CHUNK {t['default_chunk']}",
        f"#define OG1_MAX_CHUNK {t['max_chunk']}",
        f"#define OG1_IDLE_TIMEOUT_S {t['idle_timeout_s']}",
        f"#define OG1_HEARTBEAT_INTERVAL_S {t['heartbeat_interval_s']}",
        "",
        f"#define OG1_DISPLAY_WIDTH {d['width_px']}",
        f"#define OG1_DISPLAY_HEIGHT {d['height_px']}",
        f"#define OG1_TEXT_WIDTH {d['text_width_px']}",
        f"#define OG1_DEFAULT_FONT_PX {d['default_font_px']}",
        f"#define OG1_DEFAULT_LINES_PER_SCREEN {d['default_lines_per_screen']}",
        f"#define OG1_BMP_CHUNK_BYTES {d['bmp_chunk_bytes']}",
        "",
        "typedef enum {",
    ]
    for k, v in spec["status"].items():
        out.append(f"    OG1_STATUS_{k} = {hexb(v)},")
    out += [
        "} og1_status_t;",
        "",
        "typedef enum { OG1_ARM_LEFT = 0, OG1_ARM_RIGHT = 1 } og1_arm_t;",
        "",
        "typedef enum {",
        "    OG1_TARGET_BOTH = 0,",
        "    OG1_TARGET_LEFT = 1,",
        "    OG1_TARGET_RIGHT = 2",
        "} og1_target_t;",
        "",
        "typedef enum {",
        "    OG1_RSP_GENERIC = 0,",
        "    OG1_RSP_CUSTOM = 1,",
        "    OG1_RSP_ECHO_SEQ = 2,",
        "    OG1_RSP_NONE = 3",
        "} og1_response_t;",
        "",
        "/* Opcodes. Reused opcodes appear once; disambiguate via og1_cmd_t. */",
        "typedef enum {",
    ]
    seen: dict[int, str] = {}
    for c in spec["commands"]:
        if c["opcode"] in seen:
            continue
        seen[c["opcode"]] = c["name"]
        out.append(f"    OG1_OP_{c['name']} = {hexb(c['opcode'])},")
    out += ["} og1_opcode_t;", "", "typedef enum {"]
    eseen = set()
    for e in spec["events"]:
        if e["opcode"] in eseen:
            continue
        eseen.add(e["opcode"])
        out.append(f"    OG1_EVT_{e['name']} = {hexb(e['opcode'])},")
    out += [
        "} og1_event_opcode_t;",
        "",
        "/* Stable command identifiers, one per logical command. */",
        "typedef enum {",
    ]
    for i, c in enumerate(spec["commands"]):
        out.append(f"    OG1_CMD_{c['name']} = {i},")
    out += [
        f"    OG1_CMD__COUNT = {len(spec['commands'])}",
        "} og1_cmd_t;",
        "",
        "typedef struct {",
        "    const char *name;",
        "    uint8_t opcode;",
        "    int framed;",
        "    og1_target_t target;",
        "    og1_response_t response;",
        "    const uint8_t *prefix;",
        "    size_t prefix_len;",
        "    int chunked;",
        "    const char *confidence;",
        "    int headerless;",
        "} og1_cmd_info_t;",
        "",
        "/* Indexed by og1_cmd_t. */",
        "extern const og1_cmd_info_t og1_cmd_table[OG1_CMD__COUNT];",
        "",
        "const og1_cmd_info_t *og1_cmd_info(og1_cmd_t cmd);",
        "const char *og1_status_name(uint8_t status);",
        "",
    ]
    for name, members in enums_sorted(spec):
        vals = [v for _, v in members]
        if not all(isinstance(v, int) for v in vals):
            continue
        pfx = "OG1_" + "".join(
            ("_" + ch if ch.isupper() and i else ch.upper())
            for i, ch in enumerate(name)
        ).upper()
        out.append("typedef enum {")
        emitted = set()
        for k, v in members:
            if v in emitted:
                continue
            emitted.add(v)
            out.append(f"    {pfx}_{k} = {hexb(v)},")
        out.append(f"}} {pfx.lower()}_t;")
        out.append("")
    out += ["#ifdef __cplusplus", "}", "#endif", "", "#endif /* OG1_OPCODES_H */", ""]
    return "\n".join(out)


def gen_c_source(spec) -> str:
    out = [
        f"/* {BANNER} */",
        '#include "openg1/og1_opcodes.h"',
        "",
    ]
    for c in spec["commands"]:
        pre = payload_list(c)
        if pre:
            out.append(
                f"static const uint8_t pfx_{c['name']}[] = {{"
                + ", ".join(hexb(b) for b in pre)
                + "};"
            )
    out += ["", "const og1_cmd_info_t og1_cmd_table[OG1_CMD__COUNT] = {"]
    tmap = {"both": "OG1_TARGET_BOTH", "left": "OG1_TARGET_LEFT", "right": "OG1_TARGET_RIGHT"}
    rmap = {
        "generic": "OG1_RSP_GENERIC",
        "custom": "OG1_RSP_CUSTOM",
        "echo_seq": "OG1_RSP_ECHO_SEQ",
        "none": "OG1_RSP_NONE",
    }
    for c in spec["commands"]:
        pre = payload_list(c)
        ptr = f"pfx_{c['name']}" if pre else "NULL"
        out.append(
            f'    [OG1_CMD_{c["name"]}] = {{"{c["name"]}", {hexb(c["opcode"])}, '
            f'{1 if c["framing"] == "framed" else 0}, {tmap[c["target"]]}, '
            f'{rmap[c["response"]]}, {ptr}, {len(pre)}, {1 if "chunked" in c else 0}, '
            f'"{c["confidence"]}", {1 if c.get("headerless_response") else 0}}},'
        )
    out += [
        "};",
        "",
        "const og1_cmd_info_t *og1_cmd_info(og1_cmd_t cmd)",
        "{",
        "    if (cmd < 0 || cmd >= OG1_CMD__COUNT) return NULL;",
        "    return &og1_cmd_table[cmd];",
        "}",
        "",
        "const char *og1_status_name(uint8_t status)",
        "{",
        "    switch (status) {",
    ]
    for k, v in spec["status"].items():
        out.append(f'    case {hexb(v)}: return "{k}";')
    out += ['    default: return "UNKNOWN";', "    }", "}", ""]
    return "\n".join(out)


