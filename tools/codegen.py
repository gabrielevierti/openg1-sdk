def gen_java(spec) -> str:
    t, d = spec["transport"], spec["display"]
    out = [
        f"// {BANNER}",
        "package dev.openg1.protocol;",
        "",
        "import java.util.Collections;",
        "import java.util.LinkedHashMap;",
        "import java.util.Map;",
        "",
        "public final class Generated {",
        "    private Generated() {}",
        "",
        f'    public static final String SPEC_VERSION = "{spec["meta"]["spec_version"]}";',
        f'    public static final String SERVICE_UUID = "{t["service_uuid"]}";',
        f'    public static final String TX_CHAR_UUID = "{t["tx_char_uuid"]}";',
        f'    public static final String RX_CHAR_UUID = "{t["rx_char_uuid"]}";',
        f'    public static final String NAME_PREFIX = "{t["name_prefix"]}";',
        f"    public static final int DEFAULT_CHUNK = {t['default_chunk']};",
        f"    public static final int MAX_CHUNK = {t['max_chunk']};",
        f"    public static final int IDLE_TIMEOUT_S = {t['idle_timeout_s']};",
        f"    public static final int HEARTBEAT_INTERVAL_S = {t['heartbeat_interval_s']};",
        f"    public static final int DISPLAY_WIDTH = {d['width_px']};",
        f"    public static final int DISPLAY_HEIGHT = {d['height_px']};",
        f"    public static final int TEXT_WIDTH = {d['text_width_px']};",
        f"    public static final int DEFAULT_FONT_PX = {d['default_font_px']};",
        f"    public static final int DEFAULT_LINES_PER_SCREEN = {d['default_lines_per_screen']};",
        f"    public static final int BMP_CHUNK_BYTES = {d['bmp_chunk_bytes']};",
        "    public static final byte[] BMP_STORAGE_ADDRESS = {"
        + ", ".join(f"(byte) {hexb(b)}" for b in d["bmp_storage_address"])
        + "};",
        "",
    ]
    for k, v in spec["status"].items():
        out.append(f"    public static final int STATUS_{k} = {hexb(v)};")
    out.append("")
    seen: dict[int, str] = {}
    for c in spec["commands"]:
        if c["opcode"] in seen:
            continue
        seen[c["opcode"]] = c["name"]
        out.append(f"    public static final int OP_{c['name']} = {hexb(c['opcode'])};")
    out.append("")
    eseen = set()
    for e in spec["events"]:
        if e["opcode"] in eseen:
            continue
        eseen.add(e["opcode"])
        out.append(f"    public static final int EVT_{e['name']} = {hexb(e['opcode'])};")
    out.append("")
    for name, members in enums_sorted(spec):
        vals = [v for _, v in members]
        out.append(f"    public static final class {name} {{")
        out.append(f"        private {name}() {{}}")
        emitted = set()
        for k, v in members:
            if isinstance(v, int):
                if v in emitted:
                    continue
                emitted.add(v)
                out.append(f"        public static final int {k} = {hexb(v)};")
            else:
                out.append(f'        public static final String {k} = "{v}";')
        out.append("    }")
        out.append("")
    out += [
        "    public static final Map<String, CommandSpec> COMMANDS;",
        "",
        "    static {",
        "        Map<String, CommandSpec> m = new LinkedHashMap<>();",
    ]
    for c in spec["commands"]:
        pre = payload_list(c)
        arr = (
            "new byte[0]"
            if not pre
            else "new byte[]{" + ", ".join(f"(byte) {hexb(b)}" for b in pre) + "}"
        )
        out.append(
            f'        m.put("{c["name"]}", new CommandSpec("{c["name"]}", {hexb(c["opcode"])}, '
            f'{str(c["framing"] == "framed").lower()}, Target.{c["target"].upper()}, '
            f'ResponseKind.{c["response"].upper()}, {arr}, '
            f'{str("chunked" in c).lower()}, "{c["confidence"]}", '
            f'{str(bool(c.get("headerless_response"))).lower()}));'
        )
    out += [
        "        COMMANDS = Collections.unmodifiableMap(m);",
        "    }",
        "}",
        "",
    ]
    return "\n".join(out)


